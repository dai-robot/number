function norm(v) {
  return Math.round(v * 10) / 10;
}

function yearVal(y) {
  if (y >= 1900 && y <= 1999) return norm(90 + (y - 1900) / 10);
  if (y >= 2000 && y <= 2025) return norm(80 + (y - 2000) / 10);
  return null;
}

function getOccupied() {
  const R = { SSR: 4, SR: 3, R: 2, N: 1 };
  const by = new Map();
  function add(f) {
    const v = norm(f.value);
    if (v < 0 || v > 99.9) return;
    const e = by.get(v);
    if (!e || (R[f.rarity] || 0) > (R[e.rarity] || 0)) by.set(v, f);
  }
  curated.forEach(add);
  range1931.forEach(add);
  pool.forEach(add);
  Object.keys(yearEvents).forEach((y) => {
    const v = yearVal(+y);
    if (v != null) by.set(v, { value: v });
  });
  elements.forEach((el) => by.set(el.z, { value: el.z }));
  return by;
}

