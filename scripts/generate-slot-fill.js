function buildPool() {
  const facts = [];

  for (const [code, name] of Object.entries(HTTP_STATUS)) {
    const value = norm(+code / 10);
    if (value <= 99.9) {
      facts.push(makeFact(value, `HTTP ${code}`, `HTTPステータス${code}：${name}。`, "culture", code === "404" || code === "418" ? "SR" : "R", "culture", `HTTP ${code}`));
    }
  }

  for (const [code, name] of COUNTRIES) {
    const value = norm(code / 10);
    if (value <= 99.9) {
      facts.push(makeFact(value, name, `ISO3166-1 numericコード${code}。${name}。`, "culture", code === 392 ? "SSR" : "N", "culture", name));
    }
  }

  for (const [z, sym, ja, weight] of FULL_ELEMENTS) {
    const w = norm(weight);
    if (w <= 99.9) {
      facts.push(makeFact(w, `${ja}の原子量`, `${ja}（${sym}）の原子量は約${weight}。`, "science", z <= 20 ? "R" : "N", "science", ja));
    }
    if (z <= 99) {
      facts.push(makeFact(z, `${ja}（原子番号${z}）`, `${ja}の原子番号は${z}。元素記号${sym}。`, "science", z === 79 || z === 6 || z === 8 ? "SR" : "N", "science", ja));
    }
  }

  for (const [v, title, desc] of SWIM_RECORDS) {
    facts.push(makeFact(v, title, desc, "sports", "SR", "sports", title));
  }
  for (const [v, title, desc] of TRACK_RECORDS) {
    facts.push(makeFact(v, title, desc, "sports", "R", "sports"));
  }
  for (const [v, title, desc] of SONGS) {
    facts.push(makeFact(v, title, desc, "culture", "R", "culture", title));
  }
  for (const [v, title, desc] of MOUNTAINS) {
    facts.push(makeFact(v, title, desc, "science", v >= 80 ? "SR" : "R", "science", title));
  }
  for (const [v, title, desc] of JP_DAYS) {
    facts.push(makeFact(v, title, desc, "anniversary", "R", "anniversary", title));
  }
  for (const [v, title, desc] of SCIENCE) {
    facts.push(makeFact(v, title, desc, "science", "R", "science", title));
  }
  for (const [v, title, desc] of FILMS) {
    facts.push(makeFact(v, title, desc, "culture", "N", "culture", title));
  }

  return facts;
}

function main() {
  const occupied = getOccupied();
  const missing = [];
  for (let i = 0; i < 1000; i++) {
    const v = i / 10;
    if (!occupied.has(v)) missing.push(v);
  }

  const pool = buildPool();
  const assigned = new Map();
  const usedTitles = new Set();

  for (const fact of pool) {
    const v = norm(fact.value);
    if (occupied.has(v) || assigned.has(v)) continue;
    assigned.set(v, fact);
    usedTitles.add(fact.title);
  }

  const stillMissing = missing.filter((v) => !assigned.has(v));
  const failed = [];
  for (const v of stillMissing) {
    const fact = generateFallback(v);
    if (fact) {
      assigned.set(v, fact);
    } else {
      failed.push(v);
    }
  }

  if (failed.length > 0) {
    console.error("Still missing after pool:", failed.length);
    console.error(failed.join(", "));
    process.exit(1);
  }

  const output = [...assigned.values()].sort((a, b) => a.value - b.value);
  const out = `/** 自動生成: generate-slot-fill.js */\nmodule.exports = ${JSON.stringify(output, null, 2)};\n`;
  fs.writeFileSync(path.join(__dirname, "data/slot-fill.js"), out);
  console.log(`Generated slot-fill.js with ${output.length} facts for ${missing.length} missing slots`);
}

main();
