function makeFact(value, title, description, category, rarity, sourceType, shortTitle) {
  return {
    value: norm(value),
    title,
    description,
    category,
    rarity: rarity || "N",
    sourceType: sourceType || category,
    ...(shortTitle ? { shortTitle } : {}),
  };
}

function decodeDate(v) {
  const intPart = Math.floor(v);
  const decOne = Math.round((v - intPart) * 10);
  if (intPart >= 1 && intPart <= 12 && decOne >= 1 && decOne <= 9) {
    return { m: intPart, d: decOne };
  }
  if (intPart >= 10) {
    const m = Math.floor(intPart / 10);
    const d = (intPart % 10) * 10 + decOne;
    if (m >= 1 && m <= 12 && d >= 1 && d <= 31) return { m, d };
  }
  return null;
}

