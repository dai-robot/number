const namedTimes = Object.keys(real).map(Number);

function isNearNamed(time) {
  return namedTimes.some((nt) => Math.abs(time - nt) <= TOLERANCE);
}

const events = [];

for (let i = 1; i <= 12000; i++) {
  const time = Math.round(i) / 100;

  if (real[time]) {
    const [category, title, description] = real[time];
    events.push({ time, title, description, category, named: true });
    continue;
  }

  if (isNearNamed(time)) continue;

  const cat = cats[Math.floor(time * 100) % cats.length];
  events.push({
    time,
    title: `${time.toFixed(2)}秒`,
    description: facts[cat](time),
    category: cat,
    named: false,
  });
}

for (let t = 121; t <= 600; t++) {
  if (real[t]) {
    const [category, title, description] = real[t];
    events.push({ time: t, title, description, category, named: true });
    continue;
  }
  if (isNearNamed(t)) continue;
  const cat = cats[t % cats.length];
  events.push({
    time: t,
    title: `${t.toFixed(2)}秒`,
    description: facts[cat](t),
    category: cat,
    named: false,
  });
}

for (let t = 610; t <= 3600; t += 10) {
  if (real[t]) {
    const [category, title, description] = real[t];
    events.push({ time: t, title, description, category, named: true });
    continue;
  }
  if (isNearNamed(t)) continue;
  const cat = cats[t % cats.length];
  events.push({
    time: t,
    title: `${t.toFixed(2)}秒`,
    description: facts[cat](t),
    category: cat,
    named: false,
  });
}

function esc(s) {
  return s.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

const lines = ["const EVENTS_PRECISE = ["];
for (const e of events) {
  lines.push(
    `  { time: ${e.time}, title: "${esc(e.title)}", description: "${esc(e.description)}", category: "${esc(e.category)}" },`
  );
}
lines.push("];");

fs.writeFileSync("events-precise.js", lines.join("\n"));
