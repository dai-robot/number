export function getStorySecond(stoppedSeconds: number): number {
  return Math.min(30, Math.max(1, Math.round(stoppedSeconds)));
}

export function getStoryBySecond(second: number): SecondStory {
  return stories.find((story) => story.second === second) ?? stories[0];
}
